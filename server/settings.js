export function makeSettings(db) {
  return {
    get(key) {
      const r = db.get('SELECT value FROM settings WHERE key = ?', key);
      return r ? r.value : DEFAULTS[key];
    },
    int(key) { return parseInt(this.get(key), 10); },
    all() {
      const out = { ...DEFAULTS };
      for (const r of db.all('SELECT key, value FROM settings')) out[r.key] = r.value;
      return out;
    },
    set(key, value) {
      db.run('INSERT INTO settings(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value', key, String(value));
    },
  };
}
